// Bundle pinned official sources. Native-only compatibility exceptions are
// explicit, source-hash checked and recorded separately in native provenance.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createNativeCompatibilityPlugin } from '../src/runtime-compatibility.mjs';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const officialRoot = path.resolve(process.env.MINIMAX_RUNTIME_DIR ?? process.env.MINIMAX_CODE_OFFICIAL_ROOT ?? path.join(projectRoot, '../minimax-code-official'));
const { runtime: runtimePin } = JSON.parse(await readFile(path.join(projectRoot, 'upstream.lock.json'), 'utf8'));
const revision = runtimePin.commit;
const actualRevision = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: officialRoot, encoding: 'utf8' }).trim();
if (actualRevision !== revision) throw new Error(`Official source must be at ${revision}; found ${actualRevision}`);
const dirty = execFileSync('git', ['status', '--porcelain', '--untracked-files=no'], { cwd: officialRoot, encoding: 'utf8' });
if (dirty.trim()) throw new Error('Official tracked source must be clean before bundling');
const requireOfficial = createRequire(path.join(officialRoot, 'package.json'));
const { build, version: esbuildVersion } = requireOfficial('esbuild');
const { packageExportEntries } = await import(pathToFileURL(path.join(officialRoot, 'scripts/lib/package-exports.mjs')).href);
const { packageRoots } = JSON.parse(await readFile(path.join(officialRoot, 'release/extraction.json'), 'utf8'));
const aliases = Object.fromEntries(packageExportEntries(officialRoot, packageRoots).map(({ specifier, file }) => [specifier, path.join(officialRoot, file)]));
const runtime = 'packages/local-runtime-v2/src/service/miniapp/process/node-runtime';
const plugin = 'packages/local-runtime-v2/src/service/plugin-system/plugin';
const exports = [
  [`${runtime}/node-runtime.ts`, ['createMiniAppNodeRuntimeAdapter']],
  [`${runtime}/host-runner.ts`, ['runMiniAppHostRunner', 'startMiniAppModule', 'MiniAppRunnerError']],
  [`${runtime}/port-registry.ts`, ['HostMiniAppPortRegistry']],
  [`${plugin}/runtime/miniapp/candidate.ts`, ['miniAppCandidateFromPackage', 'sameMiniAppCandidate']],
  [`${plugin}/runtime/miniapp/workspace-storage.ts`, ['WorkspaceMiniAppStorage']],
  [`${plugin}/package/package-readers.ts`, ['readLocalMiniMaxPluginPackage']],
  [`${plugin}/package/filesystem.ts`, ['canonicalizePluginRoot', 'readPluginJsonObject']],
  [`${plugin}/package/miniapp/reader.ts`, ['readMiniAppMcode']],
  [`${plugin}/package/miniapp/validation.ts`, ['readMiniAppManifest']],
  [`${plugin}/package/package-contract.ts`, ['computeMiniAppPackageDigests']],
  ['packages/local-runtime-v2/src/service/plugin-system/mcp/config.ts', ['readOfficialMcpFile']],
  ['packages/tui/src/acp/control-state.ts', ['parseModelConfigValue', 'modelConfigValue']],
];
// The native Runtime must live beside the official CLI's worker and resource tree.
// Fail before producing bundles when the installer has not built the official CLI.
const nativeOutfile = path.join(officialRoot, 'dist/bot-native.mjs');
const requiredOfficialAssets = [
  ['cli.js', 'file'], ['quickjs-worker.js', 'file'], ['image-preview-worker.js', 'file'], ['emscripten-module.wasm', 'file'],
  ['photon_rs_bg.wasm', 'file'], ['configs', 'directory'], ['native', 'directory'],
  ['assets', 'directory'], ['assets/agents', 'directory'],
  ['assets/models-dev-catalog.json.gz', 'file'], ['chunks', 'directory'],
  ['vendor', 'directory'], ['internal-bin', 'directory'],
  ['mcode-tools.js', 'file'], ['matrix-mcp-stdio.js', 'file'],
];
for (const [file, kind] of requiredOfficialAssets) {
  const location = path.join(officialRoot, 'dist', file);
  const info = await stat(location).catch(() => undefined);
  if (!info || (kind === 'file' ? !info.isFile() || info.size === 0 : !info.isDirectory() || !(await readdir(location)).length)) {
    throw new Error(`Missing mandatory official build asset dist/${file}; run the official build before npm run build:official.`);
  }
}
const outputDir = path.join(projectRoot, 'src/vendor');
await mkdir(outputDir, { recursive: true });
const outfile = path.join(outputDir, 'official-miniapp.mjs');
const result = await build({
  stdin: { contents: exports.map(([file, names]) => `export { ${names.join(', ')} } from ${JSON.stringify('./' + file)};`).join('\n'), resolveDir: officialRoot, sourcefile: 'official-miniapp-entry.mjs' },
  absWorkingDir: officialRoot,
  outfile,
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  alias: aliases,
  metafile: true,
  legalComments: 'eof',
  banner: { js: `// Generated by scripts/build-official.mjs from MiniMax-AI/minimax-code ${revision}.\nimport { createRequire as __officialCreateRequire } from 'node:module';\nconst require = __officialCreateRequire(import.meta.url);` },
});
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const inputs = await Promise.all(Object.keys(result.metafile.inputs).filter((file) => file !== 'official-miniapp-entry.mjs').sort().map(async (file) => ({ path: file, sha256: sha256(await readFile(path.resolve(officialRoot, file))) })));
const dependencyRoots = [...new Set(inputs.filter(({ path: file }) => file.startsWith('node_modules/')).map(({ path: file }) => {
  const parts = file.split('/');
  return parts.slice(0, parts[1].startsWith('@') ? 3 : 2).join('/');
}))].sort();
const notices = ['# Dependency licenses\n\nGenerated from the official bundle input closure. License text is copied unchanged.\n'];
const dependencyLicenses = [];
for (const dependency of dependencyRoots) {
  const directory = path.join(officialRoot, dependency);
  const manifest = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
  const files = (await readdir(directory)).filter((file) => /^(?:licen[cs]e|copying|notice)(?:[.-].*)?$/i.test(file)).sort();
  if (!files.length) throw new Error(`No license file found for bundled dependency ${manifest.name}`);
  for (const file of files) {
    const content = await readFile(path.join(directory, file), 'utf8');
    notices.push(`\n## ${manifest.name}@${manifest.version} — ${file}\n\n${content}\n`);
    dependencyLicenses.push({ package: manifest.name, version: manifest.version, path: `${dependency}/${file}`, sha256: sha256(content) });
  }
}
await writeFile(path.join(outputDir, 'official-miniapp.NOTICES.md'), notices.join('\n'));
await writeFile(path.join(outputDir, 'official-miniapp.provenance.json'), JSON.stringify({
  repository: 'https://github.com/MiniMax-AI/minimax-code', revision, generatedBy: 'node scripts/build-official.mjs', esbuildVersion,
  sourcePolicy: 'All input sources bundled unchanged; no patches, source replacements, or lifecycle reimplementations.',
  bundle: { path: 'src/vendor/official-miniapp.mjs', sha256: sha256(await readFile(outfile)) },
  dependencyLicenses, inputs,
}, null, 2) + '\n');
await writeFile(path.join(outputDir, 'official-miniapp.LICENSE'), await readFile(path.join(officialRoot, 'LICENSE')));
console.log(`Bundled ${inputs.length} unchanged source inputs into ${path.relative(projectRoot, outfile)}`);

const { createTuiBundleModuleLocationConfig } = await import(pathToFileURL(path.join(officialRoot, 'scripts/lib/tui-npm-bundle-profile.mjs')).href);
const { cliExternalModules, cliBuildVersion } = await import(pathToFileURL(path.join(officialRoot, 'scripts/lib/cli-release.mjs')).href);
const moduleLocation = createTuiBundleModuleLocationConfig();
const nativeExports = [
  ['packages/tui/src/runtime/lifecycle.ts', ['createTuiRuntime', 'shutdownTuiRuntime']],
  ['packages/tui/src/runtime/data-dir.ts', ['prepareTuiDataDir']],
  ['packages/local-runtime-v2/src/service/agent/storage/agent-files.ts', ['AgentFiles']],
  ['packages/local-runtime-v2/src/service/agent/storage/canonical-agent-config.ts', ['readBuiltinCanonicalAgentConfig', 'serializeCanonicalAgentConfig']],
];
const nativeEntry = nativeExports.map(([file, names]) => `export { ${names.join(', ')} } from ${JSON.stringify(path.join(officialRoot, file))};`).join('\n');
const nativeFlags = {
  bundle: true, platform: 'node', target: 'node22', format: 'esm',
  external: cliExternalModules, legalComments: 'eof',
  minifyIdentifiers: true, minifyWhitespace: true,
  define: {
    ...moduleLocation.define,
    __CLI_VERSION__: JSON.stringify(cliBuildVersion(officialRoot)),
    __CLI_CHANNEL__: '"source"', __IS_NPM_BUILD__: 'true',
    __BUILD_PROFILE__: '"tui"', __TUI_BUILD_ENV__: '"prod"',
    __TUI_BUILD_VARIANT__: '"standard"', __TUI_NPM_DIST_TAG__: '"latest"',
  },
};
const compatibility = await createNativeCompatibilityPlugin({ officialRoot });
const nativeResult = await build({
  ...nativeFlags,
  plugins: [compatibility.plugin],
  stdin: { contents: nativeEntry, resolveDir: officialRoot, sourcefile: 'official-native-entry.mjs' },
  absWorkingDir: officialRoot, outfile: nativeOutfile,
  alias: aliases, metafile: true,
  banner: { js: moduleLocation.banner },
});
const nativeInputs = [];
// The complete Runtime has thousands of inputs; bound file descriptors while hashing.
for (const [file, metadata] of Object.entries(nativeResult.metafile.inputs).sort(([a], [b]) => a.localeCompare(b))) {
  nativeInputs.push({
    path: file, ...metadata,
    sha256: sha256(file === 'official-native-entry.mjs' ? nativeEntry : await readFile(path.resolve(officialRoot, file))),
  });
}
// Record the existing artifact closure as well: worker chunks and wasm are supplied
// by the official build, never copied from or rewritten in official source trees.
async function hashOfficialAsset(relativePath) {
  const absolutePath = path.join(officialRoot, relativePath);
  const info = await stat(absolutePath);
  if (info.isDirectory()) {
    const children = (await readdir(absolutePath)).sort();
    const hashes = [];
    for (const file of children) hashes.push(...await hashOfficialAsset(`${relativePath}/${file}`));
    return hashes;
  }
  return [{ path: relativePath, sha256: sha256(await readFile(absolutePath)) }];
}
const officialAssets = [...new Map((await Promise.all(requiredOfficialAssets.map(([file]) => hashOfficialAsset(`dist/${file}`)))).flat().map((asset) => [asset.path, asset])).values()].sort((a, b) => a.path.localeCompare(b.path));
const buildSources = await Promise.all([
  'scripts/build.mjs', 'scripts/lib/tui-npm-bundle-profile.mjs',
  'scripts/lib/cli-release.mjs', 'scripts/lib/package-exports.mjs', 'release/extraction.json',
].map(async (file) => ({ path: file, sha256: sha256(await readFile(path.join(officialRoot, file))) })));
await writeFile(path.join(outputDir, 'official-native.LICENSE'), await readFile(path.join(officialRoot, 'LICENSE')));
await writeFile(path.join(outputDir, 'official-native.provenance.json'), JSON.stringify({
  repository: 'https://github.com/MiniMax-AI/minimax-code', revision,
  generatedBy: 'node scripts/build-official.mjs', esbuildVersion,
  generatorSha256: sha256(await readFile(fileURLToPath(import.meta.url))),
  sourcePolicy: 'Official sources and assets are reused; only the explicit compatibilityPatches below transform native-bundle inputs. Official tracked files, CLI, workers and permission controls are unchanged.',
  compatibilityPatches: compatibility.changes,
  compatibilityGenerator: { path: 'src/runtime-compatibility.mjs', sha256: sha256(await readFile(path.join(projectRoot, 'src/runtime-compatibility.mjs'))) },
  bundle: { path: path.relative(officialRoot, nativeOutfile).split(path.sep).join('/'), relativeTo: 'runtimeDir', sha256: sha256(await readFile(nativeOutfile)) },
  build: { ...nativeFlags, alias: aliases, banner: moduleLocation.banner, entry: nativeEntry },
  buildSources, inputs: nativeInputs, officialAssets,
  outputs: nativeResult.metafile.outputs,
}, null, 2) + '\n');
console.log(`Bundled ${nativeInputs.length} native Runtime inputs with ${compatibility.changes.length} audited compatibility exceptions into ${nativeOutfile}`);
